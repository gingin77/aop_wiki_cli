"""
Cleanup annotations that were generated by experimentation with Skills and by some bugs in the AOP-KE
looping & registering code.
"""

import json

# Input files
INPUT_KE_FILE = "outputs_for_vc/annotations/ke_annotations.json"
INPUT_AOP_FILE = "outputs_for_vc/annotations/aop_based_ke_store.json"

# Output files to replace the original annotations with cleaned versions (only selected AOPs & KEs)
OUTPUT_KE_FILE = "outputs_for_vc/annotations/ke_annotations_cleaned_5-1-26.json"
OUTPUT_AOP_FILE = "outputs_for_vc/annotations/aop_annotations_cleaned_5-1-26.json"

# Annotation save for later files
OUTPUT_KE_FILE_TO_HOLD = "outputs_for_vc/annotations/hold/all_ke_annotations_captured_4-30-26.json"
OUTPUT_AOP_FILE_TO_HOLD = "outputs_for_vc/annotations/hold/all_aop_annotations_captured_4-30-26.json"

OUTPUT_EXTRA_KES = "outputs_for_vc/annotations/hold/extra_ke_annotations_captured_4-30-26.json"
OUTPUT_EXTRA_AOPS = "outputs_for_vc/annotations/hold/extra_aop_annotations_captured_4-30-26.json"

SELECTED_AOPS = [14, 39, 173, 277, 302]

def main():
    # Read inputs
    with open(INPUT_KE_FILE, "r") as f:
        ke_annotations = json.load(f)

    with open(INPUT_AOP_FILE, "r") as f:
        aop_annotations = json.load(f)

    # Make copies of the inputs to hold
    with open(OUTPUT_KE_FILE_TO_HOLD, "w") as f:
        json.dump(ke_annotations, f, indent=2)

    with open(OUTPUT_AOP_FILE_TO_HOLD, "w") as f:
        json.dump(aop_annotations, f, indent=2)

    # Collect all KEs associated with the "selected" AOPs
    kes_with_annotations_to_keep = set()
    for aop_id in SELECTED_AOPS:
        aop = aop_annotations.get(str(aop_id), {})
        for ke_id in aop:
            kes_with_annotations_to_keep.add(int(ke_id))

    # --- Filter KE annotations to only include those associated with the selected AOPs & Save ---
    ke_annotations_to_keep = {k: v for k, v in ke_annotations.items() if int(k) in kes_with_annotations_to_keep}
    with open(OUTPUT_KE_FILE, "w") as f:
        json.dump(ke_annotations_to_keep, f, indent=2)

    # --- Save extra KE annotations ---
    ke_annotations_extra = {k: v for k, v in ke_annotations.items() if k not in ke_annotations_to_keep}
    with open(OUTPUT_EXTRA_KES, "w") as f:
        json.dump(ke_annotations_extra, f, indent=2)


    # Clean up the AOP Store:
    # - Only keep AOPs that hold ke_annotations_to_keep - this will include SELECTED_AOPS + AOPs
    #   holding KEs in SELECTED_AOPS
    # - Remove KEs from AOPs that are not in ke_annotations_to_keep
    aop_annotations_cleaned = {}
    aops_dropped = {}
    for aop_id, aop_ke_ids in aop_annotations.items():
        if int(aop_id) in SELECTED_AOPS:
            aop_annotations_cleaned[aop_id] = [
                ke_id for ke_id in aop_ke_ids if ke_id in ke_annotations_to_keep
            ]
        else:
            needed_kes = [ke_id for ke_id in aop_ke_ids if ke_id in ke_annotations_to_keep]
            extra_kes = [ke_id for ke_id in aop_ke_ids if ke_id in ke_annotations_extra]
            if needed_kes:
                aop_annotations_cleaned[aop_id] = needed_kes
            if extra_kes:
                aops_dropped[aop_id] = extra_kes

    # --- Save cleaned AOP annotations ---
    with open(OUTPUT_AOP_FILE, "w") as f:
        json.dump(aop_annotations_cleaned, f, indent=2)
    # --- Save extra AOPs ---
    with open(OUTPUT_EXTRA_AOPS, "w") as f:
        json.dump(aops_dropped, f, indent=2)


if __name__ == "__main__":
    main()